export function renderCaptcha(code: string): string {
  const shapes = Array.from(code, (letter, index) => {
    let path = '';
    glyphs[letter].split(' ').forEach((row, y) =>
      Array.from(row).forEach((pixel, x) => {
        if (pixel === '1') path += `M${x * 3},${y * 4}h3v4h-3z`;
      }),
    );
    return `<path d="${path}" fill="#263d34" transform="translate(${10 + index * 27},${9 + randomInt(5)}) rotate(${randomInt(-8, 9)},8,14)"/>`;
  }).join('');
  const lines = Array.from(
    { length: 3 },
    () =>
      `<path d="M0,${randomInt(48)} Q56,${randomInt(48)} 116,${randomInt(48)}" stroke="#8bab9a" stroke-width="1" fill="none" opacity="0.55"/>`,
  ).join('');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="116" height="48" viewBox="0 0 116 48"><rect width="116" height="48" fill="#f1f5f2"/>${shapes}${lines}</svg>`;
  return `data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`;
}
